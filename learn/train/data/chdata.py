def process_and_restructure_data():
    """
    重构数据处理流程：
    1. 使用相对路径定位源和目标文件夹。
    2. 读取所有日线数据，筛选出沪深300成分股。
    3. 将数据在内存中按股票代码聚合。
    4. 对每只股票的数据排序后，一次性写入（覆盖）目标文件，避免数据重复。
    """
    # --- 配置路径 ---
    script_dir = os.path.dirname(os.path.abspath(__file__))
    # 根据你的文件结构，daily文件似乎在 'learn/train/daily/daily(1)/daily'
    # 这里我们使用相对路径来定位它
    source_dir = os.path.join(script_dir, '..', 'daily', 'daily(1)', 'daily')
    target_dir = os.path.join(script_dir, 'new')
    
    os.makedirs(target_dir, exist_ok=True)
    print(f"数据源 (预期): {os.path.abspath(source_dir)}")
    print(f"输出目录: {os.path.abspath(target_dir)}")

    # --- 数据处理 ---
    source_files = glob.glob(os.path.join(source_dir, '*.csv'))
    if not source_files:
        print(f"错误: 在目录 '{os.path.abspath(source_dir)}' 中未找到任何 .csv 文件。请确认路径是否正确。")
        return

    print(f"找到 {len(source_files)} 个日线文件，开始聚合数据...")

    stock_data_map = defaultdict(list)
    header = None

    for file_path in tqdm(sorted(source_files), desc="读取日线文件"):
        try:
            df = pd.read_csv(file_path, dtype={'secucode': str})
            
            if header is None:
                header = df.columns.tolist()

            # 统一股票代码为6位，前面补0
            df['secucode'] = df['secucode'].str.zfill(6)
            
            # 筛选沪深300成分股
            filtered_df = df[df['secucode'].isin(HS300_CODES)]
            
            # 使用 itertuples 提高遍历效率
            for row in filtered_df.itertuples(index=False):
                stock_data_map[row.secucode].append(row)
        except Exception as e:
            print(f"\n处理文件 {os.path.basename(file_path)} 时出错: {e}")

    if not stock_data_map:
        print("未在源文件中找到任何指定的沪深300成分股数据。")
        return
        
    print(f"\n数据聚合完毕，共找到 {len(stock_data_map)} 只沪深300成分股的数据，正在写入独立文件...")

    # --- 写入文件 ---
    for secucode, rows in tqdm(stock_data_map.items(), desc="写入股票数据"):
        stock_df = pd.DataFrame(rows, columns=header)
        # 按交易日升序排序并重置索引
        stock_df = stock_df.sort_values(by='tradingday').reset_index(drop=True)
        
        target_file = os.path.join(target_dir, f"{secucode}.csv")
        # 覆盖写入，确保数据不会重复
        stock_df.to_csv(target_file, index=False, encoding='utf-8-sig')

    print(f"\n数据处理完成！所有文件已保存至: {os.path.abspath(target_dir)}")

if __name__ == "__main__":
    process_and_restructure_data()